// src/i18n/translations.ts
//
// A hand-written (not runtime-translated) dictionary covering the app's
// UI chrome — navigation, buttons, headings, hints, and alert text
// across every screen. NOT the AI-generated listing content itself
// (descriptions, craft story, etc.) — that already comes back in the
// artisan's own spoken language directly from the backend (see
// lib/generateListing.js's descriptionLocal field), a separate,
// stronger mechanism that doesn't need a static dictionary at all.
//
// HONESTY NOTE: these translations were written by an LLM (Claude), not
// verified by a native speaker of each language — treat them as a
// solid demo-quality first pass, not a professionally localized app.
// A few dynamic strings (e.g. "Learned from {n} real listings") are
// composed from two static pieces joined around a number in code
// rather than a single templated sentence, since this dictionary has no
// templating engine — grammatically approximate in some languages, but
// functional and understandable.
//
// See LanguageContext.tsx for how `t()` falls back to English for any
// key not yet covered for a given language.

